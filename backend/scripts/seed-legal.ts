async function main(): Promise<void> {
  let created = 0;
  let skipped = 0;

  for (const doc of DOCS) {
    const existing = await prisma.legalDocument.findUnique({
      where: { slug_version: { slug: doc.slug, version: VERSION } },
    });

    if (existing) {
      // 已发布版本不覆盖 —— 用户同意过的那一版必须保持可举证
      if (existing.status === 'published') {
        skipped += 1;
        continue;
      }
      await prisma.legalDocument.update({
        where: { id: existing.id },
        data: { title: doc.title, content: doc.content },
      });
      created += 1;
      continue;
    }

    await prisma.legalDocument.create({
      data: {
        slug: doc.slug,
        version: VERSION,
        title: doc.title,
        content: doc.content,
        // 刻意写 draft: 模板文本未经法务审阅，不由 seed 代发布
        status: 'draft',
      },
    });
    created += 1;
  }

  console.log(`[seed:legal] 写入 ${created} 份, 跳过已发布 ${skipped} 份 (版本 ${VERSION})`);
}

main()
  .catch((e) => {
    console.error('[seed:legal] 失败:', e);
    process.exitCode = 1;
  })
  .finally(() => prisma.$disconnect());
