/**
 * 从 PostgreSQL 主源同步 SQLite 派生 schema 与迁移基线。
 *
 *   npm run prisma:sync-sqlite
 *
 * 做三件事（全部幂等）：
 *   1. schema.prisma → schema.sqlite.prisma（只换头注 / provider / generator.output）
 *   2. 用 `prisma migrate diff --from-empty --to-schema` 重新生成
 *      prisma/migrations-sqlite/<baseline>/migration.sql
 *   3. 确保 migrations-sqlite/migration_lock.toml 的 provider = "sqlite"
 *
 * 为什么迁移基线要重算而不是手工维护：SQLite 的 DDL 由 Prisma 按 schema 生成，
 * 手写极易与模型漂移。基线目录名保持不变（不新增迁移），保证已有开发库
 * 的 `_prisma_migrations` 记录仍能对上。
 */
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { deriveSqliteSchema } from './lib/sqlite-schema.mjs';

const BACKEND_ROOT = resolve(import.meta.dirname, '..');
const PRISMA_BIN = join(BACKEND_ROOT, 'node_modules', '.bin', 'prisma');
const PG_SCHEMA = join(BACKEND_ROOT, 'prisma', 'schema.prisma');
const SQLITE_SCHEMA = join(BACKEND_ROOT, 'prisma', 'schema.sqlite.prisma');
const SQLITE_MIGRATIONS = join(BACKEND_ROOT, 'prisma', 'migrations-sqlite');

function fail(message, detail) {
  console.error(`[fail] ${message}`);
  if (detail) console.error(String(detail).trim());
  process.exit(1);
}

if (!existsSync(PRISMA_BIN)) fail(`找不到 Prisma CLI: ${PRISMA_BIN}（先执行 npm ci）`);

// 1. 派生 schema
const pgSource = readFileSync(PG_SCHEMA, 'utf8');
const sqliteSource = deriveSqliteSchema(pgSource);
writeFileSync(SQLITE_SCHEMA, sqliteSource);
console.log(`[ok] 已写入 ${SQLITE_SCHEMA}`);

// 2. 迁移基线：复用已有基线目录（按目录名排序取第一个），没有则新建
if (!existsSync(SQLITE_MIGRATIONS)) mkdirSync(SQLITE_MIGRATIONS, { recursive: true });
const existing = readdirSync(SQLITE_MIGRATIONS, { withFileTypes: true })
  .filter((entry) => entry.isDirectory() && /^\d+_/.test(entry.name))
  .map((entry) => entry.name)
  .sort();
const stamp = new Date()
  .toISOString()
  .replace(/[-:TZ.]/g, '')
  .slice(0, 14);
const baselineDir = existing[0] ?? `${stamp}_baseline`;
const baselinePath = join(SQLITE_MIGRATIONS, baselineDir);
mkdirSync(baselinePath, { recursive: true });

let ddl;
try {
  ddl = execFileSync(
    PRISMA_BIN,
    [
      'migrate',
      'diff',
      '--from-empty',
      '--to-schema',
      SQLITE_SCHEMA,
      '--script',
    ],
    { cwd: BACKEND_ROOT, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] },
  );
} catch (error) {
  fail('生成 SQLite 迁移基线失败', [error.stdout, error.stderr].filter(Boolean).join('\n'));
}
writeFileSync(join(baselinePath, 'migration.sql'), ddl);
console.log(`[ok] 已重写 SQLite 迁移基线 ${baselineDir}/migration.sql`);

// 3. lock 文件
writeFileSync(
  join(SQLITE_MIGRATIONS, 'migration_lock.toml'),
  '# Please do not edit this file manually\n# It should be added in your version-control system (e.g., Git)\nprovider = "sqlite"\n',
);
console.log('[ok] SQLite migration_lock.toml provider = sqlite');
