/** 中文标点映射到最接近的 ASCII 字形，至少让标点不变成豆腐块。 */
const PUNCT_MAP = new Map([
  ['，', ','],
  ['。', '.'],
  ['：', ':'],
  ['；', ';'],
  ['！', '!'],
  ['？', '?'],
  ['（', '('],
  ['）', ')'],
  ['、', ','],
  ['—', '-'],
  ['…', '.'],
  ['“', '"'],
  ['”', '"'],
  ['‘', "'"],
  ['’', "'"],
]);

export const GLYPH_WIDTH = 5;
export const GLYPH_HEIGHT = 7;
export const GLYPH_GAP = 1;

/** 取字形；未知字符返回豆腐块。 */
export function glyphOf(ch) {
  const mapped = PUNCT_MAP.get(ch) ?? ch;
  const key = mapped.length === 1 ? mapped.toUpperCase() : '';
  return GLYPHS[key] ?? TOFU;
}

/** 文本像素宽度（含字间距）。 */
export function measureText(text, scale = 1, tracking = GLYPH_GAP) {
  if (!text) return 0;
  const chars = [...String(text)];
  return chars.length * (GLYPH_WIDTH + tracking) * scale - tracking * scale;
}

/**
 * 按像素宽度折行。
 *
 * - 含空格：按词折行；
 * - 无空格（中文/长串）：按字符折行，避免一个超长词把版面撑破。
 */
export function wrapText(text, maxWidthPx, scale = 1, tracking = GLYPH_GAP) {
  const normalized = String(text ?? '').replace(/\s+/g, ' ').trim();
  if (!normalized) return [];
  const lines = [];
  const words = normalized.includes(' ') ? normalized.split(' ') : [...normalized];
  const joiner = normalized.includes(' ') ? ' ' : '';
  let current = '';
  for (const word of words) {
    const candidate = current ? `${current}${joiner}${word}` : word;
    if (measureText(candidate, scale, tracking) <= maxWidthPx || !current) {
      current = candidate;
    } else {
      lines.push(current);
      current = word;
    }
    // 单个「词」本身超宽时继续按字符切
    while (measureText(current, scale, tracking) > maxWidthPx && [...current].length > 1) {
      const chars = [...current];
      let take = chars.length;
      while (take > 1 && measureText(chars.slice(0, take).join(''), scale, tracking) > maxWidthPx) take -= 1;
      lines.push(chars.slice(0, take).join(''));
      current = chars.slice(take).join('');
    }
  }
  if (current) lines.push(current);
  return lines;
}
